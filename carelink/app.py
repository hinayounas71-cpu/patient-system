# ---------- background job: moves unanswered alerts to backup doctor ----------
@st.cache_resource
def start_worker():
    def loop():
        sb = service_client()
        while True:
            try:
                escalate_pending(sb)
            except Exception as e:
                print("worker error:", e)
            time.sleep(30)
    t = threading.Thread(target=loop, daemon=True)
    t.start()
    return t


@st.cache_resource
def svc():
    return service_client()


start_worker()


# ---------- helpers ----------
def log_open(patient_id):
    """Audit log: add a line once each time a user opens a different patient."""
    key = "last_logged"
    if st.session_state.get(key) != patient_id:
        svc().table("audit_log").insert({
            "user_id": st.session_state.profile["id"], "patient_id": patient_id,
            "action": "opened patient record"}).execute()
        st.session_state[key] = patient_id


def staff_names(sb):
    rows = sb.table("staff_directory").select("id,full_name").execute().data
    return {r["id"]: r["full_name"] for r in rows}


def fmt_time(ts):
    return pd.to_datetime(ts).tz_convert("Asia/Karachi").strftime("%d %b %H:%M")


def generate_patient_pdf(patient, checkups_rows, advice_rows, staff_map, generated_by):
    """Generates an official downloadable clinical PDF summary for a patient."""
    pdf = FPDF()
    pdf.add_page()
    pdf.set_fill_color(15, 23, 42)
    pdf.rect(0, 0, 210, 32, 'F')
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Arial", "B", 16)
    pdf.cell(0, 14, "CLOUD-BASED PATIENT HANDLING SYSTEM", ln=True, align="C")
    pdf.set_font("Arial", "", 10)
    pdf.cell(0, 6, "Official Clinical Vitals & NEWS2 Risk Assessment Report", ln=True, align="C")

    pdf.ln(14)
    pdf.set_text_color(15, 23, 42)
    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, f"Patient Name: {patient['full_name']}   |   Age: {patient.get('age', 'N/A')} yrs", ln=True)
    pdf.set_font("Arial", "", 11)
    pdf.cell(0, 7, f"Ward: {patient['ward']}   |   Bed No: {patient['bed_no']}   |   Generated By: {generated_by}", ln=True)
    pdf.cell(0, 7, f"Report Timestamp (PKT): {dt.datetime.now(dt.timezone(dt.timedelta(hours=5))).strftime('%d %b %Y, %I:%M %p')}", ln=True)
    pdf.ln(5)

    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, "Recent Clinical Checkups & NEWS2 Scores:", ln=True)
    pdf.set_font("Arial", "B", 9)
    pdf.set_fill_color(226, 232, 240)
    headers = ["Time", "Resp", "SpO2", "Sys BP", "Pulse", "Temp", "NEWS2", "Status"]
    widths = [32, 20, 20, 22, 20, 22, 22, 32]
    for h, w in zip(headers, widths):
        pdf.cell(w, 8, h, border=1, fill=True, align="C")
    pdf.ln()

    pdf.set_font("Arial", "", 9)
    if checkups_rows:
        for r in checkups_rows[:8]:
            status = "UNSAFE (ALERT)" if r.get("is_unsafe") else "SAFE"
            vals = [
                fmt_time(r["created_at"]),
                str(r["resp_rate"]),
                f"{r['spo2']}%",
                str(r["systolic_bp"]),
                str(r["pulse"]),
                f"{r['temp']}C",
                str(r["total_score"]),
                status
            ]
            for v, w in zip(vals, widths):
                pdf.cell(w, 7, v, border=1, align="C")
            pdf.ln()
    else:
        pdf.cell(0, 8, "No clinical checkups recorded yet.", border=1, ln=True, align="C")

    pdf.ln(6)
    pdf.set_font("Arial", "B", 12)
    pdf.cell(0, 8, "Attending Doctor's Clinical Advice:", ln=True)
    pdf.set_font("Arial", "", 10)
    if advice_rows:
        for a in advice_rows[:5]:
            doc = staff_map.get(a["doctor_id"], "Doctor")
            txt = f"- [{fmt_time(a['created_at'])}] {doc}: {a['advice_text']}"
            pdf.multi_cell(0, 6, txt.encode("latin-1", "replace").decode("latin-1"))
    else:
        pdf.cell(0, 7, "No physician remarks logged yet.", ln=True)

    pdf.ln(10)
    pdf.set_font("Arial", "I", 8)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 6, "Security Verification: Protected by PostgreSQL Row-Level Security (RLS) & Immutable Audit Trail.", ln=True, align="C")

    out = pdf.output()
    if isinstance(out, (bytes, bytearray)):
        return bytes(out)
    return out.encode("latin-1", "replace")


